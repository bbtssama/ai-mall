-- =====================================================================
-- V5 · 审核链路一致性修复
--
-- 背景（2026-09-20 代码复核发现的缺陷，完整报告见
--      docs/复核-审核MQ竞态-20260920.md）：
--
--   缺陷 A（P0）幂等键版本号永不递增
--     设计意图是「同一版本只审一次，编辑后 +1 可以再审」，
--     但 biz_version 在代码里被硬编码为 1，项目也没有编辑接口去 +1，
--     于是幂等键退化成 (NOTE, noteId) 这个常量 —— 一篇笔记一生只能被审核一次。
--     后果：「重新送审」功能实际不可用（第一次 REJECT 已占用唯一键，
--           重提时 INSERT IGNORE 返回 0 → 提前 return → 状态永停 AUDITING）。
--
--   缺陷 B（P0）ERROR 流水占用终态幂等位
--     AI 调用失败时写入的 ERROR 流水与正常判定共用同一个唯一键，
--     导致一次基础设施故障（超时/限流/Key 失效）就永久堵死这篇笔记的后续重审。
--
-- 修复原则：让「幂等位」的语义回归正确 ——
--   幂等位保护的是「同一次审核请求的重复投递」，
--   而不是「这篇内容永远只能被审一次」。
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. t_note 增加 audit_version（审核版本号）
--
--    语义：发布 = 1；每调用一次「重新送审」/「编辑后重审」就 +1。
--
--    作用：让 t_audit_record 的幂等键 (biz_type, biz_id, biz_version) 能区分
--          「同一次审核的 MQ 重复投递」与「用户改完内容后的新一次审核」。
--          前者应被幂等地跳过，后者必须真正执行。
-- ---------------------------------------------------------------------
ALTER TABLE t_note
    ADD COLUMN audit_version INT NOT NULL DEFAULT 1
        COMMENT '审核版本号：发布=1，每次重新送审/编辑后重审 +1（配合审核流水唯一键做幂等）'
        AFTER status;


-- ---------------------------------------------------------------------
-- 2. t_audit_record 的唯一键纳入 status
--
--    旧：uk_biz (biz_type, biz_id, biz_version)
--    新：uk_biz (biz_type, biz_id, biz_version, status)
--
--    为什么要把 status 纳入唯一键：
--      ERROR 表示「本次审核没有得出任何结论」（AI 超时/限流/Key 失效/网络抖动），
--      它**不是一次审核结论**。旧唯一键不含 status，于是 ERROR 会和 PASS/REJECT
--      争抢同一个幂等位：
--        ERROR 落库 → 之后补审时 PASS 撞键 → INSERT IGNORE 返回 0
--        → Service 判定"重复投递"提前 return → 笔记永久停在 AUDITING。
--
--    纳入 status 之后的行为（逐条验证过）：
--      ① 同一条消息重投（同版本、同结论）→ 仍撞键 → 跳过     【幂等不破】
--      ② ERROR 之后补审成功 → PASS 与 ERROR 键不同 → 正常落库并流转 【修复 B】
--      ③ 同一版本重复报错 → 仍撞键 → 不产生重复 ERROR 行
--
--    现有数据不会因此违例：唯一键列变多只会更宽松，不会更严格。
-- ---------------------------------------------------------------------
ALTER TABLE t_audit_record
    DROP INDEX uk_biz,
    ADD UNIQUE KEY uk_biz (biz_type, biz_id, biz_version, status);
